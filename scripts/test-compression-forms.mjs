import assert from 'node:assert/strict';
import * as lib from 'pdf-lib';
import {prepareCompression} from '../public/js/pdf-compression.js';
const {PDFDocument,PDFName}=lib;
const empty=await PDFDocument.create();empty.addPage();empty.catalog.set(PDFName.of('AcroForm'),empty.context.obj({Fields:[]}));
await prepareCompression(empty,await empty.save(),lib,true);
const form=await PDFDocument.create();const page=form.addPage();
const text=form.getForm().createTextField('Policy');text.addToPage(page);text.setText('POLICY-12345');
const check=form.getForm().createCheckBox('Accepted');check.addToPage(page);check.check();
const data=await form.save();
const original=data.slice();
const copy=await PDFDocument.load(data);await prepareCompression(copy,data,lib,false);
const preserved=await PDFDocument.load(await copy.save({updateFieldAppearances:false}));
assert.equal(preserved.getForm().getTextField('Policy').getText(),'POLICY-12345');
assert.equal(preserved.getForm().getCheckBox('Accepted').isChecked(),true);
const flattened=await prepareCompression(await PDFDocument.load(data),data,lib,true);
assert.equal((await PDFDocument.load(flattened.data)).getForm().getFields().length,0);
assert.equal(form.getForm().getTextField('Policy').getText(),'POLICY-12345');
assert.deepEqual(data,original);
const special=await PDFDocument.load(data);special.catalog.lookup(PDFName.of('AcroForm')).set(PDFName.of('XFA'),special.context.obj([]));
await assert.rejects(prepareCompression(special,data,lib,true),/special form format/);
await prepareCompression(special,data,lib,false);
const signed=await PDFDocument.load(data);signed.context.register(signed.context.obj({Type:'Sig',ByteRange:[0,1,2,3]}));
for(const image of [true,false])await assert.rejects(prepareCompression(signed,data,lib,image),/digitally signed/);
console.log('PASS compression: empty form dictionaries, filled fields/checkboxes, original preservation, flattening, XFA guidance and signature protection.');
